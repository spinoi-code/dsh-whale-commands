/** 关闭人设时注入的提示（带上被关掉的人设名，避免答非所问）。 */
export function exitNote(name) {
  const who = name ? `「${name}」` : "";
  return `【人设退出】${who}人设已关闭，恢复正常的助手口吻继续工作。`;
}

/** 某个人设没有自定义提示语时的兜底文案（保证新会话/重连仍有话说）。 */
export function defaultNotice(kind, persona) {
  const name = persona?.name ?? "助手";
  const emoji = persona?.emoji ?? "🤖";
  return kind === "new"
    ? `${emoji} 新会话已就绪。${name} 的设定已继承，主人想聊什么都可以。`
    : `${emoji} 连接恢复，${name} 还在，上下文没有丢。`;
}

/**
 * 解析人设：支持 id、列表编号（1 开始）、名字/别名片段。
 * 匹配到多个则返回 null，由调用方提示「认不出」，避免默默切错人。
 */
export function resolvePersona(key) {
  const raw = String(key ?? "").trim();
  if (!raw) return null;
  const lower = raw.toLowerCase();

  const byId = PERSONAS.find((p) => p.id === lower);
  if (byId) return byId;

  const index = Number.parseInt(lower, 10);
  if (Number.isInteger(index) && String(index) === lower) {
    return PERSONAS[index - 1] ?? null;
  }

  const hits = PERSONAS.filter(
    (p) =>
      p.name.includes(raw) ||
      p.name.toLowerCase().includes(lower) ||
      p.tagline.includes(raw) ||
      (Array.isArray(p.aliases) && p.aliases.some((a) => a.toLowerCase() === lower)),
  );
  return hits.length === 1 ? hits[0] : null;
}

/**
 * 取某人设的早间问候文案。
 * dow：ISO 周几（1=周一 … 7=周日），越界/非法则用最后一条兜底。
 * 文案里的 {date} 由调用方替换成「M月D日」。
 */
export function morningText(persona, dow) {
  const lines = Array.isArray(persona?.morning) ? persona.morning : [];
  if (lines.length === 0) return "";
  const idx = Number.isInteger(dow) && dow >= 1 && dow <= 7 ? dow - 1 : lines.length - 1;
  return lines[idx] ?? lines[lines.length - 1] ?? "";
}

/** 全部人设 id（早间问候随机池用）。 */
export function personaIds() {
  return PERSONAS.map((p) => p.id);
}
